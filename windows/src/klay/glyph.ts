let cached: Path2D | null = null;

/** The glyph as a Path2D in glyph units (0…797 × 0…512). Built once. */
export function glyphPath(): Path2D {
  if (cached) return cached;
  const p = new Path2D();
  for (const s of GLYPH_SEGMENTS) {
    switch (s[0]) {
      case "M": p.moveTo(s[1], s[2]); break;
      case "L": p.lineTo(s[1], s[2]); break;
      case "C": p.bezierCurveTo(s[1], s[2], s[3], s[4], s[5], s[6]); break;
      case "Z": p.closePath(); break;
    }
  }
  cached = p;
  return p;
}
